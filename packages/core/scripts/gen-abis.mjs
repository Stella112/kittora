// Generates src/abis.ts from Foundry build output (packages/contracts/out). Run after `forge build`.
import { readFileSync, writeFileSync } from 'node:fs'
const out = new URL('../../contracts/out/', import.meta.url)
const pick = (f, c) => JSON.parse(readFileSync(new URL(`${f}/${c}.json`, out))).abi
let s = '// GENERATED by scripts/gen-abis.mjs from packages/contracts/out. Do not edit.\n'
for (const [f, c] of [['PocketVault.sol', 'PocketVault'], ['GroupKitty.sol', 'GroupKitty']])
  s += `export const ${c}Abi = ${JSON.stringify(pick(f, c), null, 2)} as const\n\n`
writeFileSync(new URL('../src/abis.ts', import.meta.url), s)
console.log('abis.ts written')
